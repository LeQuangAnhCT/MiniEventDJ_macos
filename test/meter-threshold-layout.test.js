const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const html = fs.readFileSync(path.join(__dirname, '../src/index.html'),'utf8');
const js = fs.readFileSync(path.join(__dirname, '../src/renderer.js'),'utf8');
const css = fs.readFileSync(path.join(__dirname, '../src/player-redesign.css'),'utf8');
const fragment = js.slice(js.indexOf('function drawMeter('),js.indexOf('function meterLoop()'));
assert.ok(fragment.includes('segments = 20, warningStart = 14'), 'warning starts precisely after 70%');
const leds=[];
const ctx={clearRect(){},beginPath(){},roundRect(){},fill(){leds.push(this.fillStyle)}};
const canvas={width:104,height:118,getContext:()=>ctx};
const context={$: id=> id==='#meter'?canvas:null};
vm.createContext(context);vm.runInContext(fragment,context);
context.drawMeter(1,1);
assert.deepEqual(leds.slice(0,20),[...Array(14).fill('#f5f5f5'),...Array(6).fill('#ef4444')], '100%: 14 white LEDs then 6 warning red LEDs');
assert.deepEqual(leds.slice(20),leds.slice(0,20),'both channels use the same threshold');
leds.length=0;
context.drawMeter(.5,.8);
assert.equal(leds.filter(c=>c==='#ef4444').length,2, '0.5 is below warning, 0.8 just enters red zone');
leds.length=0;
context.drawMeter(0,0);
assert.equal(leds.filter(c=>c==='#ef4444').length,0,'red LEDs remain off in silence');
assert.equal(leds.filter(c=>c==='#686868').length,40,'inactive segments use the muted white/gray base');
assert.equal(html.match(/ĐANG PHÁT/g).length>0,true);
assert.doesNotMatch(html, /class="live-track-line"/, 'duplicated current-track state removed');
assert.match(html, /class="volume-speaker-icon"/, 'master volume speaker icon');
assert.match(html, /class="control-heading tempo-heading"/, 'tempo percent above range');
assert.match(css, /\.player-grid\{align-items:stretch\}/, 'grid items stretch to the same height');
console.log('meter-threshold-layout: OK');
