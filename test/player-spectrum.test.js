const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '../src/renderer.js'), 'utf8');
const code = source.slice(source.indexOf('function drawPlayerSpectrum('), source.indexOf('function drawEqCurve('));
const calls = [];
const ctx = {};
for (const method of ['setTransform', 'clearRect', 'beginPath', 'moveTo', 'quadraticCurveTo', 'lineTo', 'stroke', 'strokeRect', 'fillText', 'closePath', 'fill', 'arc', 'fillRect']) ctx[method] = () => calls.push(method);
const canvas = { width: 0, height: 0, getBoundingClientRect: () => ({ width: 320, height: 60 }), getContext: () => ctx };
const deck = {};
const graph = { spectrum: { fftSize: 16384, getFloatFrequencyData(data) { data.fill(-35); } }, spectrumData: new Float32Array(8192) };
const context = { $: selector => selector === '#player-eq-curve' ? canvas : null, devicePixelRatio: 1, graphs: new Map([[deck, graph]]), activeDeck: deck, state: { playbackState: 'playing' }, audioContext: { sampleRate: 48000 } };
vm.createContext(context); vm.runInContext(code, context); context.drawPlayerSpectrum();
assert.ok(calls.includes('stroke') && calls.includes('fillRect'), 'draw live segmented monochrome spectrum bars');
assert.ok(calls.includes('strokeRect') && calls.includes('fillText'), 'display a grid and frequency labels');
assert.ok(!calls.includes('arc') && !calls.includes('fill'), 'do not draw draggable EQ nodes or filled blue backgrounds');
calls.length = 0; context.state.playbackState = 'paused'; context.drawPlayerSpectrum();
assert.ok(calls.includes('clearRect') && calls.includes('strokeRect') && !calls.includes('fillRect'), 'retain the grid while clearing the spectrum when music stops');
console.log('player-spectrum: OK');
